"""Stage an ingest of Tier-3 coverage into the checked-in per-title config.

`ingest_coverage_manifests.py` resolves every captured page to a module and a
load base, writes per-base seed files, and writes content-validated banks. The
banks carry captured guest bytes and are ROM-derived, so they stay in the
git-ignored build area; the *addresses* are the part worth checking in. This
copies the seed files into `re/config/` with the ROM hash and runner build id
stripped (dump fingerprints do not belong in the repo) and writes the index that
pkmn_bankgen turns into recompiler config, in two shapes:

* an alias (`[[alias]]`) is a module copied at run time to a base no bank
  declares. It becomes a `[[code_copy]]` in that CPU's config, so the CFG walk
  follows the copy into the relocated code -- `source_start` is the module's own
  guest address (`declared_base + module_span_start`), `runtime_start` is where
  the copy lives. No dumped bytes are involved.
* a seed file (`[[seed_file]]`) is one CPU's observed Tier-3 entry points from
  that same ingest, replayed as `[[entry_point]]` entries.

Only seeds that resolve to a module are staged. The `*_unresolved.toml` files
hold addresses that resolved to no ROM page at all -- runtime-materialized code
such as the ITCM copy -- and cannot be seeded into a ROM-backed bank; they need
the captured-bytes bank the ingest also writes, whose bytes stay git-ignored.

The ARM7 half of an ingest is not title-specific: the ARM7 module image is
byte-identical in all four Gen 5 titles, so it relocates to the same bases and
its observed entry points are one shared list. Those live once in
`re/config/arm7/seeds/` and every title's config references them; merge a staged
title's ARM7 seeds into that shared set instead of keeping a per-title copy.

    python tools/stage_title_config.py --ingest banks/coverage-ingest --title black
"""

import argparse
import json
import os
import re

STRIP = re.compile(r"^#.*(ROM SHA-1|Runner build)")


def sanitize(path):
    kept = [line for line in open(path, encoding="utf-8").read().splitlines()
            if not STRIP.match(line)]
    return "\n".join(kept).rstrip() + "\n"


def as_int(value):
    return int(value, 16) if isinstance(value, str) else int(value)


def span(text):
    low, _, high = text.partition("..")
    return as_int(low), as_int(high)


def alias_entries(report):
    for finding in report.get("rom_alias_findings", []):
        guest_low, guest_high = span(finding["guest_span"])
        module_low, _ = span(finding["module_span"])
        yield {
            "cpu": finding["cpu"],
            "runtime_start": guest_low,
            "source_start": as_int(finding["declared_base"]) + module_low,
            "size": guest_high - guest_low,
            "name": finding["module"].replace(".bin", "") + "_alias_%08x" % guest_low,
            "note": finding["note"],
            "pages": finding.get("pages"),
            "declared": finding["declared_base"],
            "guest_span": finding["guest_span"],
            "module_span": finding["module_span"],
        }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ingest", required=True, help="ingest --out directory")
    parser.add_argument("--title", required=True, help="title id, e.g. black")
    parser.add_argument("--out", default="re/config")
    args = parser.parse_args()

    report = json.load(open(os.path.join(args.ingest, "ingest-report.json"),
                            encoding="utf-8"))
    seed_dir = os.path.join(args.out, args.title, "seeds")
    os.makedirs(seed_dir, exist_ok=True)

    staged = []
    for name in sorted(os.listdir(os.path.join(args.ingest, "seeds"))):
        if name.endswith("_unresolved.toml"):
            continue
        with open(os.path.join(seed_dir, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(sanitize(os.path.join(args.ingest, "seeds", name)))
        staged.append(name)

    lines = [
        f"# Per-title recompilation config for {args.title}.",
        "#",
        "# Addresses and reasoning only: no ROM bytes and no dump fingerprints.",
        "# Generated by tools/stage_title_config.py from a local coverage ingest;",
        "# pkmn_bankgen --title-config turns this into per-bank recompiler config.",
        "",
        "[title]",
        f'id = "{args.title}"',
        "",
        "# A module copied at run time to a base no bank declares. The module's own",
        "# guest address is declared_base + module_span_start, and the copy lives at",
        "# guest_span_start; both resolve from the module's bytes, so no dumped bytes",
        "# are needed. Declaring the copy is what lets the recompiler's CFG walk",
        "# reach the relocated code (the finder reports these bases as 'undeclared",
        "# alias candidates' until it is told).",
    ]
    for entry in alias_entries(report):
        lines += [
            "",
            "[[alias]]",
            f'cpu           = "{entry["cpu"]}"',
            f'runtime_start = {entry["runtime_start"]:#010x}',
            f'source_start  = {entry["source_start"]:#010x}',
            f'size          = {entry["size"]:#010x}',
            f'name          = "{entry["name"]}"',
            f'note          = "{entry["note"]}"',
            "",
            f'# {entry["pages"]} captured page(s); module {entry["module_span"]} '
            f'-> guest {entry["guest_span"]}; declared base {entry["declared"]}.',
        ]
    lines += ["", "# Observed Tier-3 entry points, replayed as [[entry_point]] seeds."]
    for name in staged:
        cpu = "arm7" if name.startswith("arm7_") else "arm9"
        lines += ["", "[[seed_file]]", f'cpu  = "{cpu}"',
                  f'path = "{args.title}/seeds/{name}"']
    lines.append("")
    lines.append("# Addresses that resolved to no ROM page (the ITCM copy and other")
    lines.append("# runtime-materialized code) stay in the ingest output: they need the")
    lines.append("# captured-bytes bank, which is ROM-derived and never checked in.")
    lines.append("")

    index = os.path.join(args.out, args.title + ".toml")
    with open(index, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    print(f"wrote {index}")
    for name in staged:
        print(f"  {args.title}/seeds/{name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
